import React, { useState, useEffect } from 'react';
import { 
  ShieldCheck, AlertTriangle, ShieldAlert, Copy, Check, Share2, ExternalLink, 
  Clock, Shield, ArrowUpRight, FileText, CheckCircle2 
} from 'lucide-react';
import confetti from 'canvas-confetti';
import { ScanResult } from '../types/scanner';

interface ResultCardProps {
  result: ScanResult;
}

export const ResultCard: React.FC<ResultCardProps> = ({ result }) => {
  const [copiedReport, setCopiedReport] = useState(false);
  const [copiedLink, setCopiedLink] = useState(false);
  const [animatedScore, setAnimatedScore] = useState(0);

  // Animate score counter smoothly on result change
  useEffect(() => {
    let start = 0;
    const end = result.score;
    const duration = 900;
    const startTime = performance.now();

    const updateScore = (now: number) => {
      const elapsed = now - startTime;
      const progress = Math.min(elapsed / duration, 1);
      // easeOutExpo
      const current = Math.floor(progress === 1 ? end : end * (1 - Math.pow(2, -10 * progress)));
      setAnimatedScore(current);

      if (progress < 1) {
        requestAnimationFrame(updateScore);
      }
    };

    requestAnimationFrame(updateScore);

    // Fire confetti celebration if link is 100% verified safe (score <= 10)
    if (result.score <= 10) {
      confetti({
        particleCount: 50,
        spread: 60,
        origin: { y: 0.7 },
        colors: ['#10b981', '#06b6d4', '#3b82f6'],
      });
    }
  }, [result.score]);

  // Handle Copy Full Threat Report (Markdown formatted)
  const handleCopyReport = () => {
    const reportText = [
      `🛡️ LinkVigil Threat Intelligence Report`,
      `=======================================`,
      `Target URL: ${result.url}`,
      `Threat Score: ${result.score}/100 [${result.riskLevel.toUpperCase()}]`,
      `Verdict: ${result.verdictTitle}`,
      `Description: ${result.verdictDescription}`,
      `Resolved IP: ${result.dns.primaryIp || 'None'} (${result.ip?.country || 'Unknown Geo'}, ${result.ip?.isp || 'Unknown ISP'})`,
      `DNS Status: ${result.dns.status} | DNSSEC: ${result.dns.dnssec ? 'Yes' : 'No'}`,
      `Protocol: ${result.ssl.protocol} (${result.ssl.status})`,
      `Timestamp: ${result.timestamp}`,
      ``,
      `--- Detected Risk Flags (${result.flags.length}) ---`,
      ...result.flags.map(f => `• [${f.severity.toUpperCase()}] ${f.title}: ${f.description}`),
      ``,
      `Generated by LinkVigil (Mohamed Abouzeid)`,
    ].join('\n');

    navigator.clipboard.writeText(reportText);
    setCopiedReport(true);
    setTimeout(() => setCopiedReport(false), 2500);
  };

  const handleShareLink = () => {
    const shareUrl = `${window.location.origin}${window.location.pathname}?url=${encodeURIComponent(result.url)}`;
    navigator.clipboard.writeText(shareUrl);
    setCopiedLink(true);
    setTimeout(() => setCopiedLink(false), 2500);
  };

  // Color schemes based on Risk Level
  const isDangerous = result.riskLevel === 'dangerous';
  const isSuspicious = result.riskLevel === 'suspicious';
  const isSafe = result.riskLevel === 'safe';

  // SVG Gauge calculations
  const radius = 54;
  const circumference = 2 * Math.PI * radius;
  const strokeDashoffset = circumference - (animatedScore / 100) * circumference;

  let gaugeColor = '#10b981'; // Emerald
  let badgeBg = 'bg-emerald-500/10 text-emerald-400 border-emerald-500/30 shadow-neon-emerald';
  let badgeIcon = <ShieldCheck className="w-5 h-5 text-emerald-400" />;
  let cardBorder = 'border-emerald-500/30';
  let gaugeGlow = 'rgba(16, 185, 129, 0.4)';

  if (isDangerous) {
    gaugeColor = '#f43f5e'; // Rose
    badgeBg = 'bg-rose-500/10 text-rose-400 border-rose-500/40 shadow-neon-rose';
    badgeIcon = <ShieldAlert className="w-5 h-5 text-rose-400 animate-pulse" />;
    cardBorder = 'border-rose-500/40';
    gaugeGlow = 'rgba(244, 63, 94, 0.5)';
  } else if (isSuspicious) {
    gaugeColor = '#f59e0b'; // Amber
    badgeBg = 'bg-amber-500/10 text-amber-400 border-amber-500/30 shadow-neon-amber';
    badgeIcon = <AlertTriangle className="w-5 h-5 text-amber-400" />;
    cardBorder = 'border-amber-500/30';
    gaugeGlow = 'rgba(245, 158, 11, 0.4)';
  }

  return (
    <div className={`w-full max-w-4xl mx-auto rounded-3xl glass-panel p-6 sm:p-8 space-y-6 border ${cardBorder} shadow-2xl transition-all duration-300`}>
      {/* Top Bar: Target URL & Action Buttons */}
      <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-4 pb-6 border-b border-slate-800">
        <div className="space-y-1.5 overflow-hidden w-full md:w-auto">
          <div className="flex items-center gap-2 text-xs font-mono text-slate-400">
            <Clock className="w-3.5 h-3.5 text-cyan-400" />
            <span>Scanned in {result.scanDurationMs}ms</span>
            <span>•</span>
            <span>{new Date(result.timestamp).toLocaleTimeString()}</span>
          </div>
          <h2 className="text-base sm:text-xl font-bold font-mono text-white break-all flex items-center gap-2">
            <span>{result.url}</span>
          </h2>
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-2 flex-wrap w-full md:w-auto">
          <button
            onClick={handleCopyReport}
            className="flex-1 sm:flex-none flex items-center justify-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-medium text-slate-300 hover:text-white bg-slate-800/80 hover:bg-slate-700/80 border border-slate-700/70 transition-all duration-200"
            title="Copy formatted security threat report"
          >
            {copiedReport ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-400 font-semibold">Report Copied!</span>
              </>
            ) : (
              <>
                <FileText className="w-3.5 h-3.5 text-cyan-400" />
                <span>Copy Report</span>
              </>
            )}
          </button>

          <button
            onClick={handleShareLink}
            className="flex-1 sm:flex-none flex items-center justify-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-medium text-slate-300 hover:text-white bg-slate-800/80 hover:bg-slate-700/80 border border-slate-700/70 transition-all duration-200"
            title="Copy shareable scan permalink"
          >
            {copiedLink ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-emerald-400 font-semibold">Link Copied!</span>
              </>
            ) : (
              <>
                <Share2 className="w-3.5 h-3.5 text-cyan-400" />
                <span>Share</span>
              </>
            )}
          </button>

          <a
            href={`https://urlscan.io/search/#${encodeURIComponent(result.parsedUrl.hostname)}`}
            target="_blank"
            rel="noopener noreferrer"
            className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-medium text-slate-400 hover:text-slate-200 bg-slate-900/80 hover:bg-slate-800 border border-slate-800 transition-colors"
            title="Inspect in external URLScan Sandbox"
          >
            <span>Sandbox</span>
            <ExternalLink className="w-3 h-3" />
          </a>
        </div>
      </div>

      {/* Main Score & Verdict Section */}
      <div className="grid grid-cols-1 md:grid-cols-12 gap-6 items-center">
        {/* Left: Circular Visual Risk Gauge (0-100) */}
        <div className="md:col-span-4 flex flex-col items-center justify-center p-4 rounded-2xl bg-slate-950/50 border border-slate-800/80">
          <div className="relative w-40 h-40 flex items-center justify-center">
            {/* SVG Circular Progress Ring */}
            <svg className="w-full h-full transform -rotate-90">
              {/* Background Track */}
              <circle
                cx="80"
                cy="80"
                r={radius}
                className="text-slate-800/80"
                strokeWidth="10"
                stroke="currentColor"
                fill="transparent"
              />
              {/* Animated Progress Arc */}
              <circle
                cx="80"
                cy="80"
                r={radius}
                stroke={gaugeColor}
                strokeWidth="10"
                strokeDasharray={circumference}
                strokeDashoffset={strokeDashoffset}
                strokeLinecap="round"
                fill="transparent"
                style={{
                  filter: `drop-shadow(0 0 10px ${gaugeGlow})`,
                  transition: 'stroke-dashoffset 0.8s ease-out',
                }}
              />
            </svg>

            {/* Central Score Text */}
            <div className="absolute inset-0 flex flex-col items-center justify-center text-center">
              <span className="text-4xl font-extrabold font-mono text-white tracking-tight">
                {animatedScore}
              </span>
              <span className="text-[11px] font-mono uppercase tracking-wider text-slate-400 font-semibold">
                Risk Score
              </span>
            </div>
          </div>

          <div className="mt-3 text-center">
            <span className="text-xs font-mono text-slate-400">
              0 (Safest) &rarr; 100 (Critical)
            </span>
          </div>
        </div>

        {/* Right: Verdict Description & Risk Badge */}
        <div className="md:col-span-8 space-y-4">
          <div className="flex flex-wrap items-center gap-3">
            {/* Dynamic Status Badge */}
            <div className={`flex items-center gap-2 px-4 py-1.5 rounded-full border text-xs sm:text-sm font-bold tracking-wider font-mono uppercase ${badgeBg}`}>
              {badgeIcon}
              <span>{result.riskLevel}</span>
            </div>

            <div className="text-xs font-mono text-slate-400 bg-slate-900/60 px-3 py-1.5 rounded-lg border border-slate-800">
              {result.flags.length} Flagged {result.flags.length === 1 ? 'Anomaly' : 'Anomalies'}
            </div>
          </div>

          <div>
            <h3 className="text-xl sm:text-2xl font-bold text-white tracking-tight font-mono">
              {result.verdictTitle}
            </h3>
            <p className="mt-2 text-sm text-slate-300 leading-relaxed">
              {result.verdictDescription}
            </p>
          </div>

          {/* Key Quick Indicators Bar */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 pt-2">
            <div className="p-2.5 rounded-xl bg-slate-900/60 border border-slate-800/80">
              <span className="text-[10px] uppercase font-mono text-slate-400 block">Homograph</span>
              <span className={`text-xs font-bold font-mono ${result.heuristics.isHomograph ? 'text-rose-400' : 'text-emerald-400'}`}>
                {result.heuristics.isHomograph ? 'DETECTED' : 'Clean'}
              </span>
            </div>

            <div className="p-2.5 rounded-xl bg-slate-900/60 border border-slate-800/80">
              <span className="text-[10px] uppercase font-mono text-slate-400 block">Typosquat</span>
              <span className={`text-xs font-bold font-mono ${result.heuristics.isTyposquatting ? 'text-rose-400' : 'text-emerald-400'}`}>
                {result.heuristics.isTyposquatting ? 'DETECTED' : 'Clean'}
              </span>
            </div>

            <div className="p-2.5 rounded-xl bg-slate-900/60 border border-slate-800/80">
              <span className="text-[10px] uppercase font-mono text-slate-400 block">URLhaus DB</span>
              <span className={`text-xs font-bold font-mono ${result.urlhaus.foundInDatabase ? 'text-rose-400' : 'text-emerald-400'}`}>
                {result.urlhaus.foundInDatabase ? 'LISTED MALWARE' : 'Clean'}
              </span>
            </div>

            <div className="p-2.5 rounded-xl bg-slate-900/60 border border-slate-800/80">
              <span className="text-[10px] uppercase font-mono text-slate-400 block">Encryption</span>
              <span className={`text-xs font-bold font-mono ${result.ssl.isHttps ? 'text-emerald-400' : 'text-rose-400'}`}>
                {result.ssl.isHttps ? 'HTTPS (443)' : 'INSECURE (HTTP)'}
              </span>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
